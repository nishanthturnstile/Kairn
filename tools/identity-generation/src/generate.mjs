import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const directory = await mkdtemp(join(tmpdir(), "kairn-auth-schema-"));
try {
  const output = join(directory, "auth.ts");
  const result = spawnSync(
    "pnpm",
    [
      "exec",
      "auth",
      "generate",
      "--config",
      "auth-schema.config.ts",
      "--adapter",
      "drizzle",
      "--dialect",
      "postgresql",
      "--output",
      output,
      "--yes",
    ],
    {
      cwd: root,
      env: { ...process.env, BETTER_AUTH_TELEMETRY_DISABLED: "1" },
      stdio: "inherit",
    },
  );
  assert.equal(result.status, 0, "Pinned Better Auth schema generator failed.");
  const raw = await readFile(output, "utf8");
  assert.ok(
    raw.includes("  pgTable,"),
    "Review a changed upstream schema generator before namespace adaptation.",
  );
  const source =
    "// Generated by pnpm auth:schema:generate. Do not edit.\n// Only pgTable is namespaced; auth fields, relations, indexes and cascades remain generator-owned.\n" +
    raw
      .replace("  pgTable,", "  pgSchema,")
      .replaceAll("pgTable(", "authSchema.table(")
      .replace(
        "export const user =",
        'export const authSchema = pgSchema("authn");\n\nexport const user =',
      );
  const target = new URL("../../../packages/backend/src/identity/auth-schema.ts", import.meta.url);
  const formatted = spawnSync(
    "pnpm",
    ["exec", "vp", "fmt", `--stdin-filepath=${fileURLToPath(target)}`],
    {
      cwd: root,
      input: source,
      encoding: "utf8",
    },
  );
  assert.equal(formatted.status, 0, "Vite+ schema formatting failed.");
  if (process.argv.includes("--check"))
    assert.equal(
      await readFile(target, "utf8"),
      formatted.stdout,
      "Auth schema drift; run pnpm auth:schema:generate.",
    );
  else await writeFile(target, formatted.stdout);
  console.log("PASS pinned auth schema and namespace adaptation.");
} finally {
  await rm(directory, { recursive: true, force: true });
}
