import assert from "node:assert/strict";
import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { createOpenAPIDocument } from "@kairn/contracts/schema";
import openapiTS, { astToString } from "openapi-typescript";

const require = createRequire(import.meta.url);
const generatorRequire = createRequire(require.resolve("openapi-typescript"));
assert.equal(generatorRequire("typescript").version, "6.0.3");
assert.equal(typeof generatorRequire("typescript").factory.createIdentifier, "function");

/** @param {unknown} value @returns {unknown} */
function sorted(value) {
  if (Array.isArray(value)) return value.map(sorted);
  if (value !== null && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value)
        .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
        .map(([key, child]) => [key, sorted(child)]),
    );
  }
  return value;
}

const check = process.argv.includes("--check");
const directory = await mkdtemp(join(tmpdir(), "kairn-api-"));
try {
  const document = `${JSON.stringify(sorted(createOpenAPIDocument()), null, 2)}\n`;
  const input = join(directory, "openapi.json");
  await writeFile(input, document);
  const types = `// Generated by pnpm api:generate. Do not edit.\n${astToString(await openapiTS(pathToFileURL(input)))}`;
  const outputs = [
    {
      target: new URL("../../../packages/contracts/openapi/api.json", import.meta.url),
      content: document,
    },
    {
      target: new URL("../../../packages/contracts/generated/api.ts", import.meta.url),
      content: types,
    },
  ];
  for (const { target, content } of outputs) {
    if (check) {
      assert.equal(
        await readFile(target, "utf8"),
        content,
        `${target.href}: generated API drift; run pnpm api:generate`,
      );
    } else {
      await mkdir(new URL("./", target), { recursive: true });
      await writeFile(target, content);
    }
  }
  console.log(
    check
      ? "PASS OpenAPI and client types match fresh offline generation."
      : "Generated OpenAPI and client types from schema-only contracts.",
  );
} finally {
  await rm(directory, { recursive: true, force: true });
}
